#!/usr/bin/env python3
"""Generate short-link redirect pages from shortlinks.json.

Each entry becomes /<slug>/index.html, a tiny page that waits half a second
(so Umami can count the visit) and then forwards to the target URL.

Usage, from the repo root:
    python3 tools/make-shortlinks.py
"""
import html
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LINKS = json.loads((ROOT / "shortlinks.json").read_text())
MARKER = ".shortlink"  # marks folders this script owns, so removed links get cleaned up

TEMPLATE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>{label} · Scarlett Hao</title>
<meta name="robots" content="noindex">
<link rel="canonical" href="{url}">
<meta http-equiv="refresh" content="2; url={url}">
<script>try{{var t=localStorage.getItem("theme");if(t==="light"||t==="dark")document.documentElement.setAttribute("data-theme",t)}}catch(e){{}}</script>
<link rel="stylesheet" href="/assets/css/base.css">
<link rel="icon" href="/favicon.svg" type="image/svg+xml">
<script defer src="https://cloud.umami.is/script.js" data-website-id="b8b771e2-e860-4c8b-abf7-f1401ec97996"></script>
<style>
main {{ min-height: 70vh; display: grid; place-content: center; gap: .5rem; text-align: center; padding-left: max(20px, env(safe-area-inset-left, 0px)); padding-right: max(20px, env(safe-area-inset-right, 0px)); }}
p {{ margin: 0; color: var(--soft); }}
</style>
</head>
<body>
<main>
  <p class="mark">Scarlett Hao<span>.</span></p>
  <p>Taking you to <a href="{url}">{label}</a>&hellip;</p>
</main>
<script>setTimeout(function () {{ location.replace({url_js}); }}, 500);</script>
</body>
</html>
"""


def main():
    # Remove pages for links that were deleted from the list.
    for marker in ROOT.glob("*/" + MARKER):
        if marker.parent.name not in LINKS:
            shutil.rmtree(marker.parent)
            print("removed /" + marker.parent.name)

    for slug, link in LINKS.items():
        folder = ROOT / slug
        if folder.exists() and not (folder / MARKER).exists():
            raise SystemExit(f"/{slug} already exists and isn't a short link; pick another name.")
        folder.mkdir(exist_ok=True)
        (folder / MARKER).write_text("generated by tools/make-shortlinks.py\n")
        page = TEMPLATE.format(
            label=html.escape(link["label"]),
            url=html.escape(link["url"], quote=True),
            url_js=json.dumps(link["url"]),
        )
        (folder / "index.html").write_text(page)
        print(f"/{slug} -> {link['url']}")


if __name__ == "__main__":
    main()
